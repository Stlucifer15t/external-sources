#!/usr/bin/env python3
"""Inline shared Lua libraries into plugin scripts.

The Dreamora app runs Lua in a sandbox that removes ``require``, ``dofile``
and ``loadfile`` and provides no ``require_lib`` global.  Plugin scripts still
call ``require_lib("...")`` to load the shared libraries under ``libs/``.

This tool inlines the libraries each script needs directly into the script as a
generated block at the top, so the script loads without the shared-library
loader.  The source of truth is ``libs/**/*.lua``.

For every script (all ``*.lua`` outside ``libs/``, ``tools/`` and ``.git``):

  * collect every quoted name that matches a library basename, and follow the
    dependency chain through the library text until no new names appear (a
    superset of the real ``require_lib`` calls, which is fine);
  * insert, at the top of the script, a block delimited by BEGIN/END marker
    comments containing ``local __LIBS``, ``local __LOADERS`` and a
    forward-declared ``local require_lib``;
  * for each needed library: ``__LOADERS["name"] = function(...) <body> end``;
  * define ``require_lib(id)`` which caches the loader result, returns it and
    errors on unknown ids.

Running the tool is idempotent: the block is replaced on every run.

Usage:
    python3 tools/bundle_libs.py            # rewrite scripts in place
    python3 tools/bundle_libs.py --check    # exit 1 if any script is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
LIBS_DIR = REPO_ROOT / "libs"

BEGIN_MARKER = "-- BEGIN BUNDLED LIBRARIES (tools/bundle_libs.py)"
END_MARKER = "-- END BUNDLED LIBRARIES (tools/bundle_libs.py)"
HEADER = (
    "-- Generated by tools/bundle_libs.py — do not edit by hand. "
    "Regenerate with: python3 tools/bundle_libs.py"
)

# A single-line double-quoted or single-quoted Lua string literal. The character
# classes exclude newlines so a match cannot run past the end of its line (which
# would swallow the rest of the file and hide later library names).
QUOTED_RE = re.compile(r'"([^"\\\n]*)"|\'([^\'\\\n]*)\'')

# Directories that are never treated as scripts to bundle.
EXCLUDE_DIRS = {"libs", "tools", ".git"}


def iter_lua_files(root: Path, exclude_dirs: set[str]):
    """Yield ``*.lua`` files under *root*, skipping excluded directories."""
    for path in sorted(root.rglob("*.lua")):
        rel = path.relative_to(root)
        if any(part in exclude_dirs for part in rel.parts):
            continue
        yield path


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def load_libraries() -> dict[str, Path]:
    """Map library basename -> file path; fail on duplicate basenames."""
    libs: dict[str, Path] = {}
    for path in iter_lua_files(LIBS_DIR, exclude_dirs=set()):
        name = path.stem
        if name in libs:
            raise SystemExit(
                f"error: duplicate library name {name!r}: "
                f"{libs[name]} and {path}"
            )
        libs[name] = path
    return libs


def quoted_lib_names(text: str, lib_names: set[str]) -> set[str]:
    """Quoted strings in *text* that equal a library basename."""
    found: set[str] = set()
    for m in QUOTED_RE.finditer(text):
        value = m.group(1) if m.group(1) is not None else m.group(2)
        if value in lib_names:
            found.add(value)
    return found


def strip_block(text: str) -> str:
    """Remove the generated BEGIN/END block from *text* (idempotent)."""
    lines = text.split("\n")
    begin = end = None
    for i, line in enumerate(lines):
        if begin is None:
            if line.strip() == BEGIN_MARKER:
                begin = i
        elif line.strip() == END_MARKER:
            end = i
            break
    if begin is None:
        return text
    if end is None:  # BEGIN without END: drop from BEGIN to end of file
        return "\n".join(lines[:begin])
    return "\n".join(lines[:begin] + lines[end + 1:])


def resolve_needed(script_text: str, libs: dict[str, Path]) -> list[str]:
    """Follow the quoted-name dependency chain to a fixed point."""
    lib_names = set(libs)
    needed = quoted_lib_names(script_text, lib_names)
    queue = list(needed)
    seen: set[str] = set()
    while queue:
        name = queue.pop()
        if name in seen:
            continue
        seen.add(name)
        body = read_text(libs[name])
        for dep in quoted_lib_names(body, lib_names):
            if dep not in needed:
                needed.add(dep)
                queue.append(dep)
    return sorted(needed)


def build_block(needed: list[str], libs: dict[str, Path]) -> str:
    """Build the generated bundle block for the given libraries."""
    lines = [
        BEGIN_MARKER,
        HEADER,
        "local __LIBS = {}",
        "local __LOADERS = {}",
        "-- Forward declaration: libraries call require_lib at load time.",
        "local require_lib",
        "",
    ]
    for name in needed:
        body = read_text(libs[name]).rstrip("\n")
        lines.append(f'__LOADERS["{name}"] = function(...)')
        lines.extend(body.split("\n"))
        lines.append("end")
        lines.append("")
    lines.extend([
        "require_lib = function(id)",
        "    local cached = rawget(__LIBS, id)",
        "    if cached ~= nil then return cached end",
        "    local loader = rawget(__LOADERS, id)",
        '    if loader == nil then error("bundle_libs: unknown library id: " .. tostring(id), 2) end',
        "    local value = loader()",
        "    __LIBS[id] = value",
        "    return value",
        "end",
        END_MARKER,
    ])
    return "\n".join(lines)


def render(script_text: str, needed: list[str], libs: dict[str, Path]) -> str:
    """Return *script_text* with the generated block (re)inserted at the top."""
    rest = strip_block(script_text)
    if not needed:
        return rest
    return build_block(needed, libs) + "\n" + rest


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if any script is out of date (do not rewrite)",
    )
    args = parser.parse_args()

    libs = load_libraries()
    script_paths = list(iter_lua_files(REPO_ROOT, EXCLUDE_DIRS))

    out_of_date: list[Path] = []
    changed = 0
    for path in script_paths:
        text = read_text(path)
        # Scan the block-stripped text so an existing block cannot influence
        # the dependency set.
        needed = resolve_needed(strip_block(text), libs)
        desired = render(text, needed, libs)
        if desired != text:
            if args.check:
                out_of_date.append(path)
            else:
                path.write_text(desired, encoding="utf-8")
                changed += 1

    if args.check:
        if out_of_date:
            print(f"error: {len(out_of_date)} script(s) out of date:")
            for p in out_of_date:
                print(f"  {p.relative_to(REPO_ROOT)}")
            return 1
        print(f"bundle_libs: {len(script_paths)} scripts scanned, all up to date.")
        return 0

    print(f"bundle_libs: {len(script_paths)} scripts scanned, {changed} updated.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
